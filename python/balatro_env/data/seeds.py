"""Seed ranges: held-out eval seeds, fuzzer seeds, and fresh swarm seeds (all disjoint).

- Eval seeds: `eval_seeds.txt` next to this module, generated once by `generate_eval_seeds()` and committed.
  No training-data producer (LLM swarm, rule agents, fuzzer) may ever play them.
- Fuzzer seeds: `FUZZ` + 4 symbols, enumerated by index (`fuzz_seed(i)`).
- Swarm/training seeds: random 8-symbol seeds that are neither eval nor fuzzer seeds (`swarm_seeds()`).

Symbols follow vanilla `random_string` (functions/misc_functions.lua): 1-9, A-N, P-Z (no 0, no O).
"""

from __future__ import annotations

import random
import secrets
from functools import lru_cache
from pathlib import Path

ALPHABET = "123456789ABCDEFGHIJKLMNPQRSTUVWXYZ"
SEED_LEN = 8
FUZZ_PREFIX = "FUZZ"
EVAL_SEED_COUNT = 500
EVAL_RNG_SEED = 20261013
EVAL_SEEDS_PATH = Path(__file__).with_name("eval_seeds.txt")


def is_valid_seed(seed: str) -> bool:
    return len(seed) == SEED_LEN and all(c in ALPHABET for c in seed)


def generate_eval_seeds(count: int = EVAL_SEED_COUNT, rng_seed: int = EVAL_RNG_SEED) -> list[str]:
    """Deterministic held-out list (same output on every machine)."""
    rng = random.Random(rng_seed)
    out: list[str] = []
    seen: set[str] = set()
    while len(out) < count:
        s = "".join(rng.choice(ALPHABET) for _ in range(SEED_LEN))
        if s.startswith(FUZZ_PREFIX) or s in seen:
            continue
        seen.add(s)
        out.append(s)
    return out


def write_eval_seeds(path: Path = EVAL_SEEDS_PATH) -> None:
    header = (
        "# Held-out evaluation seeds for Balatro RL. NEVER play these in data collection\n"
        "# (LLM swarm, rule agents, fuzzer). Generated by balatro_env.data.seeds.generate_eval_seeds();\n"
        "# get training seeds with `balatro-data seeds`.\n"
    )
    path.write_text(header + "\n".join(generate_eval_seeds()) + "\n", encoding="utf-8", newline="\n")


@lru_cache(maxsize=1)
def eval_seeds() -> frozenset[str]:
    lines = EVAL_SEEDS_PATH.read_text(encoding="utf-8").splitlines()
    return frozenset(s.strip() for s in lines if s.strip() and not s.startswith("#"))


def is_eval_seed(seed: str) -> bool:
    return seed.upper() in eval_seeds()


def is_fuzz_seed(seed: str) -> bool:
    return seed.upper().startswith(FUZZ_PREFIX)


def reserved_reason(seed: str) -> str | None:
    """Why `seed` must not be used for training-data collection, or None if it is free."""
    if is_eval_seed(seed):
        return "held-out eval seed"
    if is_fuzz_seed(seed):
        return "fuzzer seed range"
    return None


def fuzz_seed(index: int) -> str:
    """The index-th fuzzer seed: FUZZ + 4 base-34 symbols."""
    n = len(ALPHABET)
    if not 0 <= index < n**4:
        raise ValueError(f"fuzz seed index out of range: {index}")
    tail = ""
    for _ in range(SEED_LEN - len(FUZZ_PREFIX)):
        index, r = divmod(index, n)
        tail = ALPHABET[r] + tail
    return FUZZ_PREFIX + tail


def swarm_seeds(count: int, rng: random.Random | None = None) -> list[str]:
    """Fresh random seeds for data collection; never eval or fuzzer seeds."""
    choice = rng.choice if rng else secrets.choice
    out: list[str] = []
    while len(out) < count:
        s = "".join(choice(ALPHABET) for _ in range(SEED_LEN))
        if reserved_reason(s) is None and s not in out:
            out.append(s)
    return out
